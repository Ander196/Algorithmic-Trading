    -- so this LEFT JOIN retains exactly one output row per stored price row.
    SELECT
        p.id AS price_id,
        p.ticker,
        p.price_date,
        p.open,
        p.high,
        p.low,
        p.close,
        p.adj_close,
        p.volume,
        p.inserted_at,
        (
            (p.ticker = 'SPY' AND p.price_date >= DATE '2000-01-01')
            OR m.ticker IS NOT NULL
        ) AS in_point_in_time_universe
    FROM public.stock_prices AS p
    LEFT JOIN membership AS m
      ON m.ticker = p.ticker
     AND p.price_date >= m.start_date
     AND (
         m.end_date_exclusive IS NULL
         OR p.price_date < m.end_date_exclusive
     )
),
ticker_summary AS (
    SELECT
        ticker,
        COUNT(*) AS total_ticker_rows,
        COUNT(*) FILTER (
            WHERE in_point_in_time_universe
        ) AS rows_inside_membership,
        COUNT(*) FILTER (
            WHERE NOT in_point_in_time_universe
        ) AS rows_outside_membership,
        MIN(price_date) FILTER (
            WHERE NOT in_point_in_time_universe
        ) AS first_outside_date,
        MAX(price_date) FILTER (
            WHERE NOT in_point_in_time_universe
        ) AS last_outside_date
    FROM price_rows
    GROUP BY ticker
)
SELECT
    'summary'::text AS record_type,
    s.ticker,
    s.total_ticker_rows,
    s.rows_inside_membership,
    s.rows_outside_membership,
    s.first_outside_date,
    s.last_outside_date,
    NULL::bigint AS price_id,
    NULL::date AS price_date,
    NULL::numeric AS open,
    NULL::numeric AS high,
    NULL::numeric AS low,
    NULL::numeric AS close,
    NULL::numeric AS adj_close,
    NULL::bigint AS volume,
    NULL::timestamptz AS inserted_at
FROM ticker_summary AS s
CROSS JOIN params AS p
WHERE p.result_mode = 'summary'
  AND s.rows_outside_membership > 0

UNION ALL

SELECT
    'detail'::text AS record_type,
    r.ticker,
    s.total_ticker_rows,
    s.rows_inside_membership,
    s.rows_outside_membership,
    s.first_outside_date,
    s.last_outside_date,
    r.price_id,
    r.price_date,
    r.open,
    r.high,
    r.low,
    r.close,
    r.adj_close,
    r.volume,
    r.inserted_at
FROM price_rows AS r
JOIN ticker_summary AS s USING (ticker)
CROSS JOIN params AS p
WHERE p.result_mode = 'detail'
  AND NOT r.in_point_in_time_universe
  AND (
      p.ticker_filter IS NULL
      OR r.ticker = UPPER(TRIM(p.ticker_filter))
  )
ORDER BY record_type, ticker, price_date NULLS FIRST, price_id;
